// Перенос docs/reference/test_checks.py (B-web-email) на WhatsApp. Номера только фиктивные.
const OWN_PHONE = '77000000001' as PhoneDigits;
const NEUTRAL = 'Мы ставим учёт вещей на RFID-метках под ключ. Подбор оборудования берём на себя.';

// Одиночная половинка суррогатной пары: такой текст API может не принять.
const LONE_SURROGATE = /[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/;

function run(text: string, clientText = ''): readonly CheckFinding[] {
  return runCodeChecks(normalizeDraft(text), { ownPhone: OWN_PHONE, clientText });
}

/** Без нормализации: как если бы конвейер забыл вызвать normalizeDraft. */
function runRaw(text: string): readonly CheckFinding[] {
  return runCodeChecks(text as NormalizedText, { ownPhone: OWN_PHONE, clientText: '' });
}

function withNeutral(text: string): string {
  return `${text} ${NEUTRAL}`;
}

function details(findings: readonly CheckFinding[]): string {
  return findings.map((finding) => finding.detail).join(' ');
}

function codes(findings: readonly CheckFinding[]): Set<string> {
  return new Set(findings.map((finding) => finding.code));
}

