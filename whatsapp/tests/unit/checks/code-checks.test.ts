describe('runCodeChecks: указание коллеги сверяется по суммам, а не по словам (ревью 29.10.2026)', () => {
  const NOTE = 'Ориентир от 1 500 000 тенге, нужен выезд';

  function withNote(text: string, note: string): readonly CheckFinding[] {
    return runCodeChecks(normalizeDraft(text), { ownPhone: OWN_PHONE, clientText: '', note });
  }

  it.each([
    'Коллега сориентировал: от 1,5 млн тенге, нужен выезд на склад.',
    'Коллега сориентировал: от 1500 тыс тенге, нужен выезд.',
    'Коллега сориентировал: от 1.5 миллиона тенге, нужен выезд.',
    'Коллега сориентировал: от 1 500 000 тенге с интеграцией 1С.',
    'Коллега сориентировал: от 1 500 000 тенге, склад 5000 м².',
    'Коллега сориентировал: от 1 500 000 тенге за 10 000 вещей.',
    'Коллега сориентировал: ориентир 1 500 000, нужен выезд.',
  ])('та же сумма в другой записи проходит: %s', (text) => {
    expect(withNote(text, NOTE)).toEqual([]);
  });

  it.each([
    ['другая сумма словом', 'Коллега подсказал: ориентир от 1 млн.'],
    [
      'другая сумма без валюты, валюта отдельно',
      'Коллега подсказал: ориентир 900 000; оплата в тенге.',
    ],
    ['другая сумма, валюта через запятую', 'Коллега подсказал: от 2 000 000, оплата в тенге.'],
    ['сумма словами без цифр', 'Коллега подсказал: стоимость в несколько тысяч.'],
    ['500к вместо 1 500 000', 'Коллега подсказал: от 500к тенге.'],
  ])('%s: нарушение', (_name, text) => {
    expect(codes(withNote(text, NOTE))).toEqual(new Set(['price']));
  });

  it('500к равно 500 000 из указания', () => {
    expect(withNote('Коллега подсказал: от 500к тенге.', 'ориентир 500 000 тенге')).toEqual([]);
  });

  it('число в указании не продолжается через «. » : «1500000. 3 недели» это 1 500 000 и срок', () => {
    const note = 'Цена 1500000. 3 недели';

    expect(withNote('Коллега подсказал: цена 1 500 000.', note)).toEqual([]);
    expect(codes(withNote('Коллега подсказал: цена 15 000 003.', note))).toEqual(
      new Set(['price']),
    );
  });

  it('количество из указания не цена: «10 000 вещей» не разрешает «10 000 тенге»', () => {
    const note = 'ориентир 1 500 000 тенге за 10 000 вещей';

    expect(codes(withNote('Коллега подсказал: от 10 000 тенге.', note))).toEqual(
      new Set(['price']),
    );
  });

  it('площадь из указания не цена', () => {
    const note = 'ориентир 1 500 000 тенге, склад 5000 м²';

    expect(codes(withNote('Коллега подсказал: от 5000 тенге.', note))).toEqual(new Set(['price']));
  });

  it('диапазон из указания: обе границы суммы', () => {
    const note = 'от 1 500 000 до 2 000 000 тенге';

    expect(withNote('Коллега подсказал: от 1 500 000 до 2 000 000 тенге.', note)).toEqual([]);
  });
});

