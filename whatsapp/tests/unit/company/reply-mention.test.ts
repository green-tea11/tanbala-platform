import { describe, expect, it } from 'vitest';
import { candidateInReply } from '../../../src/company/reply-mention.js';

// Как отправленный текст бота говорит о кандидате: никак, упоминает или спрашивает «Вы из компании X?».

describe('candidateInReply: вопрос о кандидате', () => {
  it.each([
    ['вопрос по образцу', 'ТОО «Платформа-А»', 'Вы из компании «Платформа-А», правильно?'],
    ['с городом, без формы собственности', 'ТОО «Платформа-А»', 'Платформа А, Алматы, верно?'],
    ['вопрос не первым предложением', 'Платформа-А', 'Скажите, вы из Платформа-А? Всё верно?'],
    ['вопрос из двух слов без слов подтверждения', 'Платформа-А', 'Платформа-А это ваша компания?'],
    [
      'вопрос в кавычках и дальше текст',
      'Платформа-А',
      '«Вы из компании Платформа-А, правильно?» Подскажу по учёту.',
    ],
    ['после знака вопроса скобка и восклицание', 'Платформа-А', 'Вы из Платформа-А?!)'],
    ['перевод строки внутри вопроса', 'Платформа-А', 'Вы из компании\nПлатформа-А, правильно?'],
    ['название из одного слова, есть «вы из»', 'ТОО «Склад»', 'Вы из компании «Склад»?'],
    ['название из одного слова, есть «правильно»', 'RFID', 'Вы из RFID, правильно?'],
    ['название из одного слова, есть «верно»', 'Magnum', 'Magnum, Алматы, верно?'],
  ])('%s: asked', (_label, name, text) => {
    expect(candidateInReply(text, name)).toBe('asked');
  });
});

describe('candidateInReply: только упоминание', () => {
  it.each([
    [
      'название-слово в утверждении, вопрос о другом',
      'ТОО «Склад»',
      'Ридер стоит на входе в склад. Как у вас сейчас?',
    ],
    ['название в утверждении, вопроса нет', 'Платформа-А', 'Платформа-А работает с RFID.'],
    ['короткое название-слово в вопросе о другом', 'RFID', 'Как вы сейчас ведёте учёт без RFID?'],
    ['название-слово через дефис в утверждении', 'RFID', 'RFID-метки клеят на вещь. Удобно?'],
    ['название-слово в вопросе без слов подтверждения', 'Склад', 'Сколько у вас склад занимает?'],
    ['восклицание, а не вопрос', 'Платформа-А', 'Платформа-А, здравствуйте!'],
  ])('%s: mentioned', (_label, name, text) => {
    expect(candidateInReply(text, name)).toBe('mentioned');
  });
});

describe('candidateInReply: кандидата в тексте нет', () => {
  it.each([
    ['название только частью слова', 'Альфа', 'Работаем с компанией Альфатех?'],
    ['название из одних форм собственности', 'ТОО', 'ТОО?'],
    ['пустое название', '', 'Вы из компании, правильно?'],
    ['слова названия в разных предложениях', 'Платформа А', 'Наша платформа. А ещё ридеры?'],
    ['текст пустой', 'Платформа-А', ''],
  ])('%s: none', (_label, name, text) => {
    expect(candidateInReply(text, name)).toBe('none');
  });
});

describe('candidateInReply: название карточки 2ГИС с хвостом после запятой (пункт 5 задания 01.11.2026)', () => {
  const CARD = 'Kusto Logistics Management, компания';

  it('бот спросил коротким названием: вопрос о кандидате узнаётся', () => {
    expect(candidateInReply('Kusto Logistics Management, Алматы, верно?', CARD)).toBe('asked');
    expect(candidateInReply('Вы из компании Kusto Logistics Management, правильно?', CARD)).toBe(
      'asked',
    );
  });

  it('коротким названием только упомянул: mentioned', () => {
    expect(candidateInReply('В Kusto Logistics Management это обычная задача.', CARD)).toBe(
      'mentioned',
    );
  });

  it('короткое название из одного слова: без слова подтверждения вопрос не о компании', () => {
    expect(candidateInReply('Склад у вас один?', 'Склад, компания')).toBe('mentioned');
    expect(candidateInReply('Вы из компании Склад, правильно?', 'Склад, компания')).toBe('asked');
  });
});
