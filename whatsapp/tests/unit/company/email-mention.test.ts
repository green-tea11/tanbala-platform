import { describe, expect, it } from 'vitest';
import { mentionsOurEmail } from '../../../src/company/email-mention.js';

// Сказал ли бот клиенту о нашем письме: после этого фраза «мы писали вам на почту» больше не разрешена.

describe('mentionsOurEmail', () => {
  it.each([
    'Мы писали вам на почту, рады, что вы откликнулись.',
    'Здравствуйте! Мы вам писали недавно о метках.',
    'Вы, наверное, получили наше письмо.',
    'Мы отправляли вам письмо о складском учёте.',
    'Писали на вашу почту на прошлой неделе.',
    'Найду наше письмо и вернусь к разговору. Расскажите, чем занимается компания?',
    'МЫ НАПИСАЛИ ВАМ!',
    'Спасибо, что ответили на письмо, которое мы вам отправили.',
  ])('«%s»: да', (text) => {
    expect(mentionsOurEmail(text)).toBe(true);
  });

  it.each([
    'Расскажите, что у вас на хранении?',
    'Можем прислать предложение письменно.',
    'Данные уходят в вашу 1С, интеграцию делает наш сотрудник.',
    'Клиенты часто пишут нам на почту.',
    'Опишите, пожалуйста, вашу задачу.',
    'Описали это в письме коллеге. Вам удобно продолжить здесь?',
    '',
  ])('«%s»: нет', (text) => {
    expect(mentionsOurEmail(text)).toBe(false);
  });
});

describe('ревью этапа 3: писал клиент, а не мы', () => {
  it.each(['Как вы писали, у вас 1С.', 'Вы писали, что у вас склад в Алматы.'])(
    '«%s» не о нашем письме',
    (text) => {
      expect(mentionsOurEmail(text)).toBe(false);
    },
  );

  it('«Мы писали вам на почту» по-прежнему о нашем письме', () => {
    expect(mentionsOurEmail('Мы писали вам на почту, рады продолжить здесь.')).toBe(true);
  });
});
