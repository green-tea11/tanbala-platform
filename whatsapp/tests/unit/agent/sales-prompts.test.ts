import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { Knowledge } from '../../../src/agent/knowledge.js';
import { buildSystem } from '../../../src/agent/prompts.js';

const KNOWLEDGE: Knowledge = {
  owner: '# Tanbala: что должен знать агент\n\nЦены не называй.\n',
  whatsapp: '# Tanbala в WhatsApp\n\nОдна или две фразы.\n',
  consult: '# Tanbala в WhatsApp: как консультировать\n',
  version: 'v1',
};

/**
 * Текст владельца от 27.10.2026, уточнён 30.10.2026 (метки на товар, ручной сканер) и 01.11.2026 (учёт в 1С, без 1С
 * можем её поставить, веб-платформа дополнительно к 1С): общий принцип работы, его можно объяснять любому клиенту.
 */
const OWNER_PRINCIPLE =
  'Метку клеят на товар. Ридеры с антеннами стоят на входах и выходах, а не на каждой полке. Когда товар проходит через вход или выход, система сама отмечает, что он пришёл или ушёл. Сканировать вручную по одной не нужно. Ридер видит сразу всю партию. Ручным сканером проходят вдоль полок и сверяют список, не вскрывая коробок. Данные уходят в 1С клиента (интеграцию делает наш сотрудник). Если 1С у клиента нет, её можно поставить. Наша веб-платформа с учётом идёт дополнительно к 1С, а не вместо неё.';

function instruction(purpose: 'reply' | 'review'): string {
  return buildSystem(KNOWLEDGE, purpose).at(-1)?.text ?? '';
}

describe('инструкция ответа: продажа через боли и общий принцип', () => {
  const text = instruction('reply');

  it('принцип работы из consult.md можно объяснять любому клиенту', () => {
    expect(text).toMatch(/Принцип работы из consult.md можно объяснять любому клиенту/);
  });

  it('боль уверенно, как то, что обычно бывает в таком бизнесе, сразу с плюсом; не как факт о клиенте (30.10.2026)', () => {
    expect(text).toMatch(/бери боль оттуда, иначе из consult.md по бизнесу клиента/);
    expect(text).toMatch(
      /Называй её уверенно, как то, что обычно бывает в таком бизнесе \(«обычно», «часто»\), и сразу закрывай плюсом/,
    );
    expect(text).toMatch(/Не утверждай, что точно знаешь, как у клиента/);
  });

  it('без цифр о компании клиента, без пересказа собранного и ссылок на сайт и 2ГИС', () => {
    expect(text).toMatch(/Цифр о компании клиента \(площадь, число филиалов\) не называй/);
    expect(text).toMatch(/о масштабе спрашивай сам/);
    expect(text).toMatch(/Не пересказывай клиенту, что мы о нём знаем или собрали/);
    expect(text).toMatch(/не ссылайся на его сайт, 2ГИС или другие источники/);
  });
});

describe('инструкция проверки: принцип не нарушение, пересказ собранного нарушение', () => {
  const text = instruction('review');

  it('пункт 4: нарушение только готовое решение для этого клиента; принцип работы не нарушение', () => {
    expect(text).toMatch(
      /4\. [^\n]*готовое решение: что поставить, сколько и где именно у этого клиента/,
    );
    expect(text).toMatch(
      /принцип работы \(метка на товаре, антенны на входе и выходе, ручной сканер, запись названия товара в метку, 1С клиента или наша веб-платформа\)/,
    );
  });

  it('нарушение: пересказ собранного, ссылка на сайт или 2ГИС, боль как факт о клиенте', () => {
    expect(text).toMatch(/Рассказ клиенту, что мы о нём знаем или собрали/);
    expect(text).toMatch(/ссылка на его сайт, 2ГИС или другие источники/);
    expect(text).toMatch(/трудность из справки, поданная как факт о клиенте/);
  });

  it('не нарушение (30.10.2026): боль уверенно и сразу с плюсом, сильные стороны и принцип работы', () => {
    expect(text).toMatch(
      /боль, поданная уверенно как то, что обычно или часто бывает в таком бизнесе, сразу с плюсом/,
    );
    expect(text).toMatch(/сильные стороны из consult.md, боль и плюс из consult.md/);
  });

  it('пункт 1 не ловит боль похожих компаний; пункт 10 не ловит вопрос о компании и разрешённое «писали»', () => {
    expect(text).toMatch(
      /1\. [^\n]*Сильные стороны из consult.md \(F1, F2 и дальше\), боли и плюсы из consult.md и трудности из справки о компании есть в документах/,
    );
    expect(text).toMatch(
      /10\. [^\n]*Вопрос, из той ли он компании, и разрешённое справкой «мы писали вам на почту» сюда не относятся/,
    );
    expect(text).toMatch(/«мы писали вам на почту», если в справке сказано, что мы писали/);
  });
});

describe('knowledge/whatsapp.md: принцип работы и продажа', () => {
  const whatsapp = readFileSync(new URL('../../../knowledge/whatsapp.md', import.meta.url), 'utf8');

  it('принцип работы дословно, как подтвердил владелец, и про всю партию', () => {
    expect(whatsapp).toContain('### Как работает учёт (подтверждено владельцем)');
    expect(whatsapp).toContain(OWNER_PRINCIPLE);
    expect(whatsapp).toContain('Ридер видит сразу всю партию.');
    expect(whatsapp).toMatch(
      /Это не решение под объект клиента: сколько ридеров и где именно их ставить/,
    );
  });

  it('раздел о продаже: боль у похожих компаний с вопросом, без цифр и пересказа, запреты остаются', () => {
    expect(whatsapp).toContain('## Как продавать');
    expect(whatsapp).toMatch(
      /Боль называй уверенно, как то, что обычно бывает в таком бизнесе, и сразу закрывай её плюсом/,
    );
    expect(whatsapp).toMatch(/бери её из справки о компании, если она есть, иначе из consult.md/);
    expect(whatsapp).toMatch(/о масштабе спрашивай сам/);
    expect(whatsapp).toMatch(/не ссылайся на его сайт, 2ГИС и другие источники/);
    expect(whatsapp).toMatch(/Запреты остаются: цены, сроки, срочность и давление/);
  });
});
