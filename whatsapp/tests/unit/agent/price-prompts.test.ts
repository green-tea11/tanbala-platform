import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { Knowledge } from '../../../src/agent/knowledge.js';
import { buildSystem } from '../../../src/agent/prompts.js';

const KNOWLEDGE: Knowledge = {
  owner: '# Tanbala: что должен знать агент\n\nЦены не называй.\n',
  whatsapp: '# Tanbala в WhatsApp\n\nОдна или две фразы.\n',
  consult: '# Tanbala в WhatsApp: как консультировать\n',
  version: 'v1',
};

/** Фраза владельца от 27.10.2026 при передаче чата после вопроса цены. */
const PRICE_HANDOFF = 'Цена сильно зависит от объёма. Уточню у коллеги и вернусь к вам.';

function instruction(purpose: 'review' | 'interest'): string {
  return buildSystem(KNOWLEDGE, purpose).at(-1)?.text ?? '';
}

describe('вопрос цены: проверка и оценка интереса', () => {
  it('проверка не отклоняет вопрос о недостающем для передачи по цене и фразу «Ориентир коллега назовёт...»', () => {
    const text = instruction('review');
    expect(text).toMatch(
      /в обычном ответе о цене: «Ориентир коллега назовёт, когда поймём ваш объект», «цена сильно зависит от объёма» и вопросы о том, чего не хватает для передачи \(компания, вещи, материал, число вещей, город, помещение, 1С\)/,
    );
    expect(text).toContain(
      'Фраза «Ориентир коллега назовёт, когда поймём ваш объект» допустима в обычном ответе на вопрос цены: это не обещание за коллегу и не передача.',
    );
    expect(text).not.toContain('чтобы коллега сразу назвал ориентир');
  });

  it('проверка не отклоняет вопросы квалификации: компания, вещи, материал, город, помещение и другое', () => {
    expect(instruction('review')).toContain(
      'вопрос клиенту о его компании и бизнесе, вещах, упаковке, материале, городе, помещении, площади, числе вещей и их движении, нынешнем учёте, трудностях и 1С;',
    );
  });

  it('проверка не отклоняет два или три связанных вопроса в одном сообщении (решение 29.10.2026 вечером)', () => {
    expect(instruction('review')).toContain(
      'два или три коротких связанных вопроса в одном сообщении (например, о вещах, упаковке и материале или о городе, помещении и числе вещей) и одна полезная фраза рядом с ними: число вопросов в сообщении не нарушение;',
    );
  });

  it('проверка не отклоняет «цена сильно зависит от объёма» и фразу передачи владельца', () => {
    const text = instruction('review');
    expect(text).toMatch(/без чисел [^\n]*«цена сильно зависит от объёма»/);
    expect(text).toContain(`в сообщении о передаче «${PRICE_HANDOFF}»`);
  });

  it('оценка интереса: первый вопрос цены без задачи hot не даёт, четвёртый вопрос и отказ отвечать дают', () => {
    const text = instruction('interest');
    expect(text).toMatch(
      /hot: клиент согласился, что трудность у него есть, или рассказал о своей задаче/,
    );
    expect(text).toMatch(
      /или спрашивает цену четвёртый раз; или отказывается отвечать на вопросы и спрашивает цену; или просит живого человека/,
    );
    expect(text).not.toMatch(/второй раз/);
    expect(text).toMatch(
      /Первый вопрос цены без рассказа о задаче и без согласия, что трудность есть, hot не даёт/,
    );
  });

  it('оценка интереса: поля минимума и сигналы последних сообщений клиента', () => {
    const text = instruction('interest');
    for (const field of [
      'items: ',
      'packaging: ',
      'material: ',
      'city: ',
      'premises: ',
      'turnover: ',
      'currentTracking: ',
    ]) {
      expect(text).toContain(field);
    }
    expect(text).toMatch(/oneCName: какая у клиента 1С/);
    expect(text).toMatch(/problemAgreed: true, если клиент согласился, что трудность у него есть/);
    expect(text).toMatch(/priceAsked: true, если в них клиент спрашивает цену/);
    expect(text).toMatch(/refused: true, если в них клиент отказывается отвечать/);
  });
});

describe('knowledge/whatsapp.md: один голос (решение владельца 29.10.2026)', () => {
  const whatsapp = readFileSync(new URL('../../../knowledge/whatsapp.md', import.meta.url), 'utf8');

  it('клиенту сотрудник Tanbala это «коллега», фраза передачи «Уточню у коллеги и вернусь к вам»', () => {
    expect(whatsapp).toMatch(/Клиенту менеджера называй коллегой/);
    expect(whatsapp).toContain('«Уточню у коллеги и вернусь к вам.»');
    expect(whatsapp).not.toMatch(/Передал ваш вопрос|Передал вопрос|передал специалисту/);
    // «он вам напишет» только как запрет: «не «он вам напишет»».
    expect(whatsapp.match(/он вам напишет/g)).toHaveLength(1);
    expect(whatsapp).toContain('не «он вам напишет»');
  });

  it('«специалист» только в цитате документа и в правиле одного голоса', () => {
    const lines = whatsapp.split('\n').filter((line) => /специалист/.test(line));

    expect(lines).toHaveLength(2);
    expect(lines[0]).toContain('«расскажет специалист в WhatsApp»');
    expect(lines[1]).toMatch(/Слово «специалист» из документа клиенту не пиши/);
  });
});

describe('knowledge/whatsapp.md: вопрос цены', () => {
  const whatsapp = readFileSync(new URL('../../../knowledge/whatsapp.md', import.meta.url), 'utf8');

  it('минимум перед передачей по цене (решение владельца 29.10.2026): пять пунктов', () => {
    expect(whatsapp).toContain('### Вопрос цены');
    expect(whatsapp).toMatch(/Перед передачей по цене коллеге нужен минимум/);
    for (const item of [
      '1. Название компании.',
      '2. Что учитывать: какие вещи и из какого материала.',
      '3. Примерное число вещей.',
      '4. Город и тип помещения.',
      '5. Есть ли 1С.',
    ]) {
      expect(whatsapp).toContain(item);
    }
  });

  it('что выяснять: четыре группы по порядку, необязательное только в группу (решение 29.10.2026 вечером)', () => {
    for (const item of [
      'группами по порядку:',
      '1. Компанию и чем она занимается.',
      '2. Что учитывать: какие вещи, в чём они (коробки, паллеты, поштучно), из какого материала.',
      '3. Где и сколько: город, тип помещения (склад, открытая площадка, магазин), примерное число вещей.',
      '4. 1С: есть ли и какая конфигурация.',
      'в сообщении не больше одного блока из двух или трёх коротких связанных вопросов одной группы, по возможности одним предложением',
      'отдельным сообщением ради них не спрашивай',
    ]) {
      expect(whatsapp).toContain(item);
    }
  });

  it('фраза «Ориентир коллега назовёт...» только в ответ на вопрос цены (решение 29.10.2026 вечером)', () => {
    expect(whatsapp).toContain(
      'Фразу «Ориентир коллега назовёт, когда поймём ваш объект.» пиши только в ответ на вопрос цены: если клиент цену не спрашивал, её не пиши.',
    );
    expect(buildSystem(KNOWLEDGE, 'reply').at(-1)?.text ?? '').toContain(
      'Фразу «Ориентир коллега назовёт...» пиши только в ответ на вопрос цены: если клиент в последних сообщениях цену не спрашивал, её не пиши, это проверяет код.',
    );
  });

  it('цена без минимума: ответ из знаний, «Ориентир коллега назовёт...», вопросы группы; с минимумом передача', () => {
    expect(whatsapp).toMatch(/Клиент спросил цену, а минимума нет: чат не передавай/);
    expect(whatsapp).toContain(
      'напиши «Ориентир коллега назовёт, когда поймём ваш объект.» и задай вопросы следующей группы, где чего-то не хватает',
    );
    expect(whatsapp).not.toContain('чтобы коллега сразу назвал ориентир');
    expect(whatsapp).toMatch(/Один блок вопросов за сообщение, без анкеты/);
    expect(whatsapp).not.toMatch(
      /по одному вопросу|не больше одного вопроса|Один вопрос за сообщение/,
    );
    expect(whatsapp).toContain(
      `Минимум собран, и клиент спрашивает цену: напиши «${PRICE_HANDOFF}» и передай чат`,
    );
  });

  it('сразу без минимума: просьба о человеке, отказ отвечать, четвёртый вопрос цены, жалоба; третий больше не повод', () => {
    expect(whatsapp).toMatch(
      /Без минимума передавай чат сразу, только если клиент прямо просит живого человека, отказывается отвечать на вопросы, спрашивает цену в четвёртый раз или жалуется/,
    );
    expect(whatsapp).not.toMatch(/второй раз|третий раз/);
  });

  it('уровни и «Что писать клиенту» согласованы с правилами цены', () => {
    expect(whatsapp).toMatch(/- Горячий: клиент согласился, что трудность у него есть/);
    expect(whatsapp).toContain(`- Клиент спрашивал цену: «${PRICE_HANDOFF}»`);
    expect(whatsapp).toMatch(/На вопрос «сколько стоит» действуй по правилам «Вопрос цены»/);
  });

  it('уведомление менеджеру: компания или «не определена», ссылка на карточку, подтверждённые трудности', () => {
    expect(whatsapp).toMatch(
      /компанию клиента \(или «не определена»\) со ссылкой на её карточку и трудности, которые клиент подтвердил/,
    );
  });

  it('уведомление менеджеру: что из минимума для цены собрано и что выяснить не удалось', () => {
    expect(whatsapp).toMatch(/что из минимума для цены собрано и что выяснить не удалось/);
  });

  it('без тире', () => {
    expect(whatsapp).not.toMatch(/[\u2012-\u2015\u2212]/);
  });
});

