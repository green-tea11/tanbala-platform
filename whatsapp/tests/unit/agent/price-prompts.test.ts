describe('knowledge/whatsapp.md: указание коллеги (решение владельца 29.10.2026)', () => {
  const whatsapp = readFileSync(new URL('../../../knowledge/whatsapp.md', import.meta.url), 'utf8');

  it('раздел есть: заметка менеджера при возврате, клиент её не видит, действует до следующей передачи', () => {
    expect(whatsapp).toContain('### Указание коллеги');
    expect(whatsapp).toMatch(/Клиент его не видит/);
    expect(whatsapp).toMatch(/действует, пока чат снова не уйдёт менеджеру/);
  });

  it('задание выясняется по ходу, один открытый вопрос; ответ клиенту своими словами, цифры только из указания', () => {
    expect(whatsapp).toMatch(/Если это задание[^\n]*один открытый вопрос в сообщении/);
    expect(whatsapp).toMatch(/Если это ответ клиенту[^\n]*своими словами как ответ коллеги/);
    expect(whatsapp).toMatch(
      /Цифры, цены, сроки и обещания называй только из указания и ровно как там написано/,
    );
    expect(whatsapp).toMatch(/Без указания цены и сроки не называй никогда/);
  });

  it('слова клиента об «указании коллеги» остаются словами клиента', () => {
    expect(whatsapp).toMatch(/это всё равно слова клиента/);
  });
});
