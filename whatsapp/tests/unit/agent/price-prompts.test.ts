import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { interestSchema } from '../../../src/agent/interest.js';
import type { Knowledge } from '../../../src/agent/knowledge.js';
import { buildSystem } from '../../../src/agent/prompts.js';

const KNOWLEDGE: Knowledge = {
  owner: '# Tanbala: что должен знать агент\n\nЦены не называй.\n',
  whatsapp: '# Tanbala в WhatsApp\n\nОдна или две фразы.\n',
  consult: '# Tanbala в WhatsApp: как консультировать\n',
  version: 'v1',
};

/** Фраза при передаче чата в финале и после вопроса цены при понятной задаче (решение владельца 30.10.2026). */
const PRICE_HANDOFF = 'Я уточню у коллеги решение и ориентир под вашу задачу.';

function instruction(purpose: 'review' | 'interest'): string {
  return buildSystem(KNOWLEDGE, purpose).at(-1)?.text ?? '';
}

describe('вопрос цены: проверка и оценка интереса', () => {
  it('проверка не отклоняет «Ориентир коллега назовёт...» и вопрос по ходу разговора в ответе на вопрос цены', () => {
    const text = instruction('review');
    expect(text).toContain(
      'в обычном ответе на вопрос цены, сроков или договора «Ориентир коллега назовёт, когда поймём вашу задачу», «цена сильно зависит от объёма» и вопрос по ходу разговора;',
    );
    expect(text).not.toContain('ваш объект');
    expect(text).not.toContain('чтобы коллега сразу назвал ориентир');
  });

  it('проверка не отклоняет вопросы для расчёта (решение владельца 30.10.2026)', () => {
    expect(instruction('review')).toContain(
      'вопрос клиенту о его компании и бизнесе, о том, что лежит на хранении, сколько этого, сколько нового приходит, как учитывают и проверяют сейчас, о проходах, пересчёте полок, 1С и городе;',
    );
  });

  it('анкета: два и больше предложения с вопросом нарушение; два вопроса в одном предложении и рассказ перед вопросом можно (02.11.2026)', () => {
    expect(instruction('review')).toContain(
      '11. Анкета: в сообщении два и больше предложения с вопросом (со знаком вопроса или просьбой «Расскажите», «Подскажите»), три и больше вопроса в одном предложении или вопрос о компании вместе с другим вопросом. Два вопроса в одном предложении можно. Рассказ, боль и плюс вопросами не считаются: вопрос, знает ли клиент RFID, или вопрос о компании («Компания X, Алматы, верно?») после рассказа это один вопрос.',
    );
  });

  it('проверка не отклоняет фразы передачи владельца', () => {
    expect(instruction('review')).toContain(
      `в сообщении о передаче «${PRICE_HANDOFF}» или «Уточню у коллеги и вернусь к вам.»;`,
    );
  });

  it('оценка интереса: hot как у кода (решение владельца 30.10.2026): готов к расчёту, цена при понятной задаче, просьба о человеке', () => {
    const text = instruction('interest');
    expect(text).toContain(
      'hot: клиент готов к расчёту (для расчёта известно всё: чем занимается компания, что лежит на хранении, сколько этого, сколько нового приходит в месяц, сколько проходов учитывать, есть ли 1С и какая, город) или спрашивает цену, сроки или договор, когда задача понятна (клиент согласился, что трудность у него есть, или рассказал о своей задаче, и известно, что лежит на хранении и сколько этого); или просит живого человека.',
    );
    expect(text).toContain(
      'Вопрос цены, сроков или договора, пока задача не понятна, hot не даёт.',
    );
    expect(text).not.toMatch(
      /четвёртый раз|второй раз|отказывается отвечать на вопросы и спрашивает цену/,
    );
    // Уровень по-прежнему чат не передаёт.
    expect(text).toContain('Чат ты не передаёшь: уровень только сохраняется');
  });

  it('оценка интереса: priceAsked и про сроки и договор (решение владельца 30.10.2026)', () => {
    expect(instruction('interest')).toContain(
      'priceAsked: true, если в них клиент спрашивает цену, стоимость, бюджет, сроки или договор («сколько стоит», «какая цена», «когда сможете поставить», «как заключить договор»), в том числе снова; иначе false;',
    );
    expect(interestSchema.shape.priceAsked.description).toBe(
      'true, если в последних сообщениях клиента (после последней реплики assistant) есть вопрос о цене, стоимости, сроках или договоре; иначе false.',
    );
  });

  it('оценка интереса: поля минимума и сигналы последних сообщений клиента', () => {
    const text = instruction('interest');
    for (const field of [
      'items: ',
      'packaging: ',
      'material: ',
      'city: ',
      'premises: ',
      'turnover: ',
      'currentTracking: ',
    ]) {
      expect(text).toContain(field);
    }
    expect(text).toMatch(/oneCName: какая у клиента 1С/);
    expect(text).toMatch(/problemAgreed: true, если клиент согласился, что трудность у него есть/);
    expect(text).toMatch(/priceAsked: true, если в них клиент спрашивает цену/);
    expect(text).toMatch(/refused: true, если в них клиент отказывается отвечать/);
  });
});

describe('knowledge/whatsapp.md: один голос (решение владельца 29.10.2026)', () => {
  const whatsapp = readFileSync(new URL('../../../knowledge/whatsapp.md', import.meta.url), 'utf8');

  it('клиенту сотрудник Tanbala это «коллега», фраза передачи «Уточню у коллеги и вернусь к вам»', () => {
    expect(whatsapp).toMatch(/Клиенту менеджера называй коллегой/);
    expect(whatsapp).toContain('«Уточню у коллеги и вернусь к вам.»');
    expect(whatsapp).not.toMatch(/Передал ваш вопрос|Передал вопрос|передал специалисту/);
    // «он вам напишет» только как запрет: «не «он вам напишет»».
    expect(whatsapp.match(/он вам напишет/g)).toHaveLength(1);
    expect(whatsapp).toContain('не «он вам напишет»');
  });

  it('«специалист» только в цитате документа и в правиле одного голоса', () => {
    const lines = whatsapp.split('\n').filter((line) => /специалист/.test(line));

    expect(lines).toHaveLength(2);
    expect(lines[0]).toContain('«расскажет специалист в WhatsApp»');
    expect(lines[1]).toMatch(/Слово «специалист» из документа клиенту не пиши/);
  });
});

describe('knowledge/whatsapp.md: вопрос цены', () => {
  const whatsapp = readFileSync(new URL('../../../knowledge/whatsapp.md', import.meta.url), 'utf8');

  it('финал (решение владельца 30.10.2026): всё для расчёта известно, сводка и фраза, чат уходит; минимума и пятого сообщения нет', () => {
    expect(whatsapp).toContain('### Финал');
    expect(whatsapp).toContain(
      `коротко перескажи задачу словами клиента и напиши «${PRICE_HANDOFF}» Вопросов не задавай: чат уходит коллеге.`,
    );
    expect(whatsapp).toContain(
      'Пятое сообщение клиента и собранный «минимум» чат больше не передают: ты ведёшь разговор до финала.',
    );
    expect(whatsapp).not.toMatch(/Перед передачей по цене коллеге нужен минимум/);
  });

  it('что выяснять для расчёта и как спрашивать: по одному открытому вопросу, без анкеты (решение 30.10.2026)', () => {
    for (const item of [
      'Для расчёта по ходу разговора узнай: чем занимается компания, что лежит на хранении и в каком виде, сколько этого примерно, сколько нового приходит в месяц, сколько проходов нужно учитывать, есть ли 1С и какая, город.',
      'Вопросы задавай по одному: в сообщении один открытый вопрос, на который отвечают рассказом, а не «да» или «нет»; два вопроса можно соединить в одно предложение.',
      'Анкету из нескольких вопросов подряд не задавай.',
      'Про металл и жидкости сам не спрашивай.',
    ]) {
      expect(whatsapp).toContain(item);
    }
    expect(whatsapp).not.toMatch(/группами по порядку|блока из двух или трёх/);
  });

  it('фраза «Ориентир коллега назовёт...» только в ответ на вопрос цены, сроков или договора (решения 29.10 и 02.11.2026)', () => {
    expect(whatsapp).toContain(
      'Фразу «Ориентир коллега назовёт, когда поймём вашу задачу.» пиши только в ответ на вопрос цены, сроков или договора: если клиент об этом не спрашивал, её не пиши.',
    );
    expect(buildSystem(KNOWLEDGE, 'reply').at(-1)?.text ?? '').toContain(
      'Фразу об ориентире пиши только в ответ на вопрос цены, сроков или договора: если клиент в последних сообщениях об этом не спрашивал, её не пиши, это проверяет код.',
    );
  });

  it('вопрос цены: задача не понятна, ответ и «Ориентир коллега назовёт...»; понятна, передача с фразой владельца', () => {
    expect(whatsapp).toContain(
      '- Задача клиента ещё не понятна (так сказано в блоке данных): чат не передавай.',
    );
    expect(whatsapp).toContain(
      'напиши «Ориентир коллега назовёт, когда поймём вашу задачу.» и задай один вопрос по ходу разговора',
    );
    expect(whatsapp).toContain(
      `и он спрашивает цену, сроки или договор: напиши «${PRICE_HANDOFF}» и передай чат.`,
    );
    expect(whatsapp).not.toContain('чтобы коллега сразу назвал ориентир');
    expect(whatsapp).not.toContain('ваш объект');
  });

  it('третий вопрос цены и два ухода от вопросов подряд передаёт система (решение владельца 30.10.2026)', () => {
    expect(whatsapp).toContain(
      '- Клиент спрашивает цену третий раз или два раза подряд уходит от вопросов: чат передаёт система сама.',
    );
    expect(whatsapp).not.toMatch(/четвёртый раз/);
  });

  it('уровни и «Что писать клиенту» согласованы с правилами цены', () => {
    expect(whatsapp).toMatch(/- Горячий: для расчёта известно всё, и клиент готов к расчёту/);
    expect(whatsapp).toContain(`- Финал и вопрос цены, когда задача понятна: «${PRICE_HANDOFF}»`);
    expect(whatsapp).toMatch(/На вопрос «сколько стоит» действуй по правилам «Вопрос цены»/);
  });

  it('уведомление менеджеру: компания или «не определена», ссылка на карточку, подтверждённые трудности', () => {
    expect(whatsapp).toMatch(
      /компанию клиента \(или «не определена»\) со ссылкой на её карточку и трудности, которые клиент подтвердил/,
    );
  });

  it('уведомление менеджеру: что для расчёта известно и чего не хватает, причина с цитатой, рассказанное', () => {
    expect(whatsapp).toMatch(
      /что для расчёта известно и чего не хватает, причину передачи с цитатой клиента, какие сильные стороны клиенту уже рассказаны/,
    );
  });

  it('без тире', () => {
    expect(whatsapp).not.toMatch(/[\u2012-\u2015\u2212]/);
  });
});

