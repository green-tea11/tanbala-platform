// Данные проверок кодом: перенос docs/reference/checks.py (B-web-email) на WhatsApp.
// В JS \w, \b и \d знают только ASCII даже с флагом u, а в Python 3 они Unicode,
// поэтому «буква, цифра или _» здесь [\p{L}\p{N}_], а цифра \p{Nd}. Квантификаторы перед другими
// частями шаблона ограничены сверху: ответ модели зависит от текста клиента, долгие регулярки
// недопустимы. Шаблоны с флагом g используются только через matchAll или replace;
// CYRILLIC_LETTER и LATIN_LETTER без g: только для test().

const W = String.raw`[\p{L}\p{N}_]`;

/** Не больше трёх предложений в сообщении: в чате «2–3 коротких предложения» вместо 5–8 в письме. */
export const MAX_SENTENCES = 3;

/** Не больше 300 знаков на всё сообщение: «короткие» предложения. */
export const MAX_CHARS = 300;

/** Сколько знаков контекста показывать вокруг найденного фрагмента. */
export const CONTEXT_CHARS = 25;

/** Длинный найденный фрагмент обрезается в замечании: замечания уходят модели при повторе. */
export const MAX_FRAGMENT_CHARS = 60;

/** Номер сравнивается с нашим по последним цифрам: +7, 8 и номер без кода страны совпадают. */
export const PHONE_COMPARE_DIGITS = 10;

/** Хосты, на которые разрешены ссылки. В чате ссылок нет совсем, поэтому список пуст. */
export const ALLOWED_LINK_HOSTS: ReadonlySet<string> = new Set<string>();

/** Аббревиатуры, которые не считаются капслоком. */
export const ALLOWED_CAPS: ReadonlySet<string> = new Set(['RFID', 'ТОО', 'БИН', 'ИИН']);

/** Невидимые символы (\p{Cf}) и управляющие (\p{Cc}) кроме переноса строки: их убирает normalizeDraft. */
export const INVISIBLE_EXCEPT_NEWLINE = /(?!\n)[\p{Cf}\p{Cc}]/gu;

// --- тире ---

export const DASH_PATTERNS: readonly RegExp[] = [/[—–―−‒]/gu, /(?:(?<=\s)|^)[-‐‑](?=\s|$)/gmu];

// --- цены (казахская «теңге», «баға» и «пайыз» тоже) ---

const CURRENCY = String.raw`(?:те[нң]ге|тг(?![а-я])|тнг(?![а-я])|₸|руб(?![а-я])|рубл${W}*|₽|\$|€|usd|kzt|tenge|rub(?![a-z])|eur(?![a-z])|cny(?![a-z])|долл${W}*|бакс${W}*|юан${W}*|сом(?:а|ов)?(?!\p{L})|у\.\s?е\.?|евро(?!\p{L}))`;

/**
 * Сленг сумм: «два ляма», «пол-ляма», «1,5 мульта», «1,5кк», «300 т.р.», «1.5M», «1,5 mln». Это всегда деньги. Латинская
 * «M» только вплотную к числу.
 */
const MONEY_SLANG = String.raw`(?<!\p{L})(?:пол-?)?лям(?:а|ов|ы|у)?(?!\p{L})|(?<!\p{L})мульт(?:а|ов|ы)?(?!\p{L})|(?<=\p{Nd})[кk][кk](?!\p{L})|(?<=\p{Nd}\s{0,2})т\.?\s?р\.?(?!\p{L})|(?<=\p{Nd})m(?!\p{L})|(?<=\p{Nd}\s{0,2})mln(?!\p{L})`;

/** Цена за штуку: число вплотную перед «за штуку», «за метку», «за склад», «за всё». */
const PER_UNIT = String.raw`(?<![\p{Nd}\p{L}])\p{Nd}[\p{Nd}\s.,]{0,20}?\s{1,3}за\s{1,3}(?:штук|шт|метк|единиц|комплект|склад|объект|вс[её])\p{L}{0,3}(?!\p{L})`;

/**
 * Число с этими словами не сумма, а количество: «5 тысяч вещей», «500к меток», «10 000 коробок». Его не ловят шаблоны
 * сумм словами и не берёт сверка цены с заметкой (checks/amounts.ts).
 */
export const COUNT_NOUN = String.raw`(?:вещ|штук|шт|метк|меток|единиц|позици|товар|наименовани|короб|паллет|поддон|артикул|предмет|издели|sku|сотрудник|человек)\p{L}{0,6}`;

/** Единицы длины и площади: «5000 м²» (после NFKC «м2»), «до 20 метров». */
export const UNIT_NOUN = String.raw`(?:(?:м|см|мм|км|га)(?!\p{L})|кв\.?\s?м(?!\p{L})|квадрат\p{L}{0,6}|метр\p{L}{0,3}|сантиметр\p{L}{0,3}|миллиметр\p{L}{0,3}|километр\p{L}{0,3}|гектар\p{L}{0,3})`;

/** Срок и дата: «3 недели», «2 дня», «15 ноября». */
export const TIME_NOUN = String.raw`(?:секунд|минут|мин|час|дн|день|дней|недел|месяц|мес|год|лет|квартал|смен|январ|феврал|март|апрел|ма[яй]|июн|июл|август|сентябр|октябр|ноябр|декабр)\p{L}{0,6}`;

/** Миллионы после числа: «1,5 млн», «2 миллиона». Такая сумма почти всегда деньги. */
const MILLION_MULTIPLIER = String.raw`(?:млн|млрд|миллион\p{L}{0,4}|миллиард\p{L}{0,4})(?!\p{L})`;

/** Тысячи после числа: «900 тыс», «5 тысяч», «500 мың». Слово целиком: «тысячи» не обрезается до «тыся». */
const THOUSAND_MULTIPLIER = String.raw`(?:тыс\p{L}{0,6}(?!\p{L})|мың(?!\p{L}))`;

/**
 * Конец утверждения после тысяч: конец текста, «!», перенос строки или точка, но точка сокращения «тыс.» только в
 * конце текста: «около 2 тыс. заказов» не конец.
 */
const STATEMENT_END = String.raw`(?=\s{0,3}(?:[!\n]|$)|(?<!(?<!\p{L})тыс)\.(?:\s|$)|(?<=(?<!\p{L})тыс)\.\s{0,3}$)`;

/** Справа не количество и не площадь: «5 тысяч вещей» и «3 тысячи квадратов» не сумма. */
const NOT_COUNT_AFTER = String.raw`(?!\.?\s{0,3}(?:${COUNT_NOUN}|${UNIT_NOUN}))`;

/**
 * Тысячи числом или словом: «900 тыс», «500к», «полторы тысячи», «полутора тысяч». Так же пишут и количество («до 10
 * тысяч или больше?», «около 10к инструментов»), поэтому это цена только с признаком цены в той же части фразы
 * (PRICE_CONTEXT, checks/code-checks.ts) или в конце утверждения («Внедрение примерно 500к.»).
 */
const THOUSAND_AMOUNT = String.raw`(?:(?<![\p{Nd}\p{L}])\p{Nd}[\p{Nd}\s.,]{0,20}?(?:\s{0,3}${THOUSAND_MULTIPLIER}|(?<=\p{Nd})[кk](?!\p{L}))|(?<!\p{L})пол(?:тор|утор)\p{L}{0,3}\s{1,3}${THOUSAND_MULTIPLIER})${NOT_COUNT_AFTER}`;

/** Тысячи, которые цена только с признаком цены в той же части фразы (PRICE_CONTEXT). */
export const THOUSAND_PRICE_PATTERNS: readonly RegExp[] = [new RegExp(THOUSAND_AMOUNT, 'giu')];

/**
 * Признак цены в части фразы: валюта, слово цены, «за штуку» и подобные. Без флага g: только для test(). Текст в любом
 * регистре.
 */
export const PRICE_CONTEXT =
  /(?<!\p{L})(?:те[нң]ге|tenge|тг|тнг|kzt|руб\p{L}*|rub|rur|usd|долл\p{L}*|бакс\p{L}*|евро|eur|юан\p{L}*|cny|у\.\s?е|цен[аыуе]|стоимост\p{L}*|стоит|стоят|обойд[её]тся|выйдет|выход(?:ит|ят)|бюджет\p{L}*|ориентир\p{L}*|вилк\p{L}*|бағ\p{L}*|оплат\p{L}*)(?!\p{L})|[₸₽$€]|(?<!\p{L})за\s{1,3}(?:штук|шт|метк|единиц|комплект|склад|объект|вс[её])/iu;

// Число рядом со словом цены. Берётся целиком: (?<!\p{Nd}) и (?!\p{Nd}) не дают откатиться к его части.
// Не цена: «1С» и число с единицей расстояния («стоит на воротах, читает до 20 метров»).
const PRICE_NUMBER = String.raw`(?<!\p{Nd})(?!1\s{0,2}[сc](?!\p{L}))\p{Nd}{1,15}(?!\p{Nd})(?![.,]\p{Nd})(?!\s{0,2}(?:м|см|мм|км|метр\p{L}{0,3}|сантиметр\p{L}{0,3}|миллиметр\p{L}{0,3}|километр\p{L}{0,3})(?!\p{L}))`;

// Сумма словом без цифр: «пяти тысяч», «2 млн».
const PRICE_AMOUNT_WORD = String.raw`(?<!\p{L})(?:тысяч|тыс|млн|миллион)\p{L}*`;

const PRICE_WORD = String.raw`(?<!\p{L})(?:цена|цены|цену|стоимость|стоит|стоят|обойд[её]тся|выйдет|бюджет\p{L}*|баға\p{L}*)(?!\p{L})`;

// «Ориентир» и «вилка» называют цену, только если сразу за ними число или сумма словом: «ориентир от 1,5 млн».
// «Чтобы коллега сразу назвал ориентир, подскажите...» не цена: между словом и числом нет «,;.!?», не больше 20 знаков,
// а за числом не количество и не срок («ориентировочно 2 недели» ловят стоп-слова, если это обещание).
const ESTIMATE_WORD = String.raw`(?<!\p{L})(?:ориентир|вилк)\p{L}{0,10}(?:(?!${COUNT_NOUN})[^\p{Nd}.!?\n,;]){0,20}`;
const NOT_QUANTITY_AFTER = String.raw`(?![\p{Nd}\s.,]{0,20}(?:${COUNT_NOUN}|${TIME_NOUN}))`;

// «Какой процент товара теряется?» спрашивает о задаче клиента, а не называет цену.
const AFTER_QUESTION_WORD = String.raw`(?<!(?:какой|какая|какую|сколько)(?:\s{1,5}\p{L}{1,30}){0,2}\s{1,5})`;

export const PRICE_PATTERNS: readonly RegExp[] = [
  new RegExp(String.raw`\p{Nd}[\p{Nd}\s.,]{0,30}${CURRENCY}`, 'giu'),
  /(?<!\p{L})(?:те[нң]ге|tenge|kzt|rub|usd|eur|cny)(?!\p{L})|₸|₽|\$|€/giu,
  new RegExp(String.raw`сэконом${W}*|экономи[яию]\s{1,5}\p{Nd}`, 'giu'),
  new RegExp(
    String.raw`${PRICE_WORD}[^.!?\n]{0,30}?(?:${PRICE_NUMBER}|${PRICE_AMOUNT_WORD})`,
    'giu',
  ),
  // Сверх образца (ревью 29.10.2026): ориентир и вилка с числом, число со словом суммы («900 тыс», «500к»), сумма
  // словом без цифр («полтора миллиона»). «Тысяч» без цифр не цена: «для нескольких тысяч вещей».
  new RegExp(
    String.raw`${ESTIMATE_WORD}(?:${PRICE_NUMBER}${NOT_QUANTITY_AFTER}|(?<!\p{L})(?:тысяч|тыс|млн|миллион)\p{L}{0,6}(?!\p{L})${NOT_COUNT_AFTER})`,
    'giu',
  ),
  new RegExp(
    String.raw`(?<![\p{Nd}\p{L}])\p{Nd}[\p{Nd}\s.,]{0,20}?\s{0,3}${MILLION_MULTIPLIER}${NOT_COUNT_AFTER}`,
    'giu',
  ),
  // Тысячи в конце утверждения: «Внедрение примерно 500к.» Остальные тысячи: THOUSAND_PRICE_PATTERNS.
  new RegExp(String.raw`${THOUSAND_AMOUNT}${STATEMENT_END}`, 'giu'),
  new RegExp(
    String.raw`(?<!\p{Nd}\s{0,2})(?<!\p{L})(?:млн|млрд|миллион\p{L}{0,4}|миллиард\p{L}{0,4})(?!\p{L})${NOT_COUNT_AFTER}`,
    'giu',
  ),
  // Сверх образца (ревью 29.10.2026, второй круг): сленг сумм, «выходит около двухсот тысяч», цена за штуку.
  new RegExp(MONEY_SLANG, 'giu'),
  new RegExp(
    String.raw`(?<!\p{L})выход(?:ит|ят)(?!\p{L})[^.!?\n]{0,30}?(?:${PRICE_NUMBER}${NOT_QUANTITY_AFTER}|(?<!\p{L})(?:тысяч|тыс|млн|миллион)\p{L}{0,6}(?!\p{L})${NOT_COUNT_AFTER})`,
    'giu',
  ),
  new RegExp(PER_UNIT, 'giu'),
  // Сверх образца: валюта и проценты словами и одиночный «%»
  /(?<!\p{L})(?:рубл\p{L}*|доллар\p{L}*|бакс\p{L}*|юан\p{L}*|евро)(?!\p{L})|(?<!\p{L})у\.\s?е\./giu,
  new RegExp(
    String.raw`${AFTER_QUESTION_WORD}(?<!\p{L})(?:процент\p{L}*|пайыз\p{L}*)(?!\p{L})`,
    'giu',
  ),
  /%/gu,
];

// --- стоп-слова (текст заранее в нижнем регистре и с «е» вместо «ё») ---

// «час» только в формах часа: «часть работы» не срок.
const HOURS = String.raw`час(?:а|ов|у|ам|ами|ах)?(?!\p{L})`;

