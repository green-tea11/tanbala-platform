/** До конца предложения нет «?»: это не вопрос клиенту. */
const NOT_QUESTION = String.raw`(?![^.!?\n]{0,80}\?)`;

/** Единица срока для обещаний со словами «займёт», «уложимся» (текст уже с «е» вместо «ё»). */
const DEADLINE_UNIT = String.raw`(?:минут|час|дн|день|дня|дней|сутк|недел|месяц|год|лет)\p{L}{0,4}(?!\p{L})`;

const MONTH = String.raw`(?:январ|феврал|март|апрел|ма[яй]|июн|июл|август|сентябр|октябр|ноябр|декабр)\p{L}{0,3}`;

/**
 * Сроки и обещания времени: их заметка для бота разрешает, если тот же фрагмент есть в ней с тем же отрицанием
 * («не за 2 недели» не то же, что «за 2 недели»).
 */
const PROMISE_STOP_SOURCES: readonly string[] = [
  String.raw`(?<![а-я])за\s{1,5}\p{Nd}{1,10}(?:\s{0,3}[-‐‑–—]\s{0,3}\p{Nd}{1,10})?\s{0,3}(?:(?:дн|недел|месяц|минут)${W}*|${HOURS})`,
  String.raw`(?<![а-я])сроки?\s{1,5}(?:внедрени|поставк)${W}*`,
  String.raw`(?<![а-я])(?:ответим|свяжемся|позвоним|перезвоним)[^.!?\n]{0,20}(?:сегодня|${HOURS}|минут)`,
  // Сверх образца: обещания времени ответа и сроков (план: «не обещает конкретное время ответа»)
  String.raw`(?<!\p{L})(?:сейчас|скоро|сегодня|завтра)(?:\s{1,5}\p{L}{1,30}){0,2}?\s{1,5}(?:подключ|напиш|ответ|позвон|свяж)\p{L}*`,
  String.raw`(?<!\p{L})(?:подключ|напиш|ответ|позвон|свяж)\p{L}*(?:\s{1,5}\p{L}{1,30}){0,2}?\s{1,5}(?:сейчас|скоро|сегодня|завтра)(?!\p{L})`,
  String.raw`(?<!\p{L})(?:напиш|ответ|позвон|свяж|подключ)\p{L}*[^.!?\n]{0,30}?(?<!\p{L})(?:в\s{1,3}течение|через)(?!\p{L})[^.!?\n]{0,20}?(?<!\p{L})(?:${HOURS}|(?:минут|дн|день|недел)\p{L}*)`,
  String.raw`(?<!\p{L})(?:внедр|постав|установ|запуст|сдела|настро)\p{L}*[^.!?\n]{0,30}?(?<!\p{L})(?:за|через|в\s{1,3}течение)(?!\p{L})[^.!?\n]{0,20}?(?<!\p{L})(?:${HOURS}|(?:дн|день|недел|месяц)\p{L}*)`,
  // Сверх образца (ревью 29.10.2026, второй круг): «займёт 2 недели», «уложимся в две недели», «к 15 ноября», «до
  // конца месяца», «за выходные». Вопрос клиенту («Сколько времени занимает инвентаризация?») не обещание.
  String.raw`(?<!\p{L})(?:займ|занима|уложим|уложат|уложусь)\p{L}{0,6}${NOT_QUESTION}[^.!?\n]{0,25}?(?<!\p{L})${DEADLINE_UNIT}`,
  String.raw`(?<!\p{L})к\s{1,3}\p{Nd}{1,2}(?:-?(?:му|го|е|ое))?\s{1,3}${MONTH}${NOT_QUESTION}`,
  String.raw`(?<!\p{L})до\s{1,3}конца\s{1,3}(?:(?:этой|этого|следующей|следующего)\s{1,3})?(?:недел|месяц|года|квартал)\p{L}{0,3}${NOT_QUESTION}`,
  String.raw`(?<!\p{L})за\s{1,3}(?:(?:эти|одни|ближайшие)\s{1,3})?выходные${NOT_QUESTION}`,
];

const toStopPattern = (source: string): RegExp => new RegExp(source, 'giu');

/** Реклама и обещания результата: нарушение всегда, с заметкой для бота тоже. */
export const PROMO_STOP_PATTERNS: readonly RegExp[] = PROMO_STOP_SOURCES.map(toStopPattern);

/** Сроки и обещания времени: с заметкой для бота допустимы, если они есть в ней с тем же отрицанием. */
export const PROMISE_STOP_PATTERNS: readonly RegExp[] = PROMISE_STOP_SOURCES.map(toStopPattern);

