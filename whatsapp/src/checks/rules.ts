export const DASH_PATTERNS: readonly RegExp[] = [/[—–―−‒]/gu, /(?:(?<=\s)|^)[-‐‑](?=\s|$)/gmu];

// --- цены (казахская «теңге», «баға» и «пайыз» тоже) ---

const CURRENCY = String.raw`(?:те[нң]ге|тг(?![а-я])|тнг(?![а-я])|₸|руб(?![а-я])|рубл${W}*|\$|€|usd|kzt|долл${W}*|евро(?!\p{L}))`;

// Число рядом со словом цены. Берётся целиком: (?<!\p{Nd}) и (?!\p{Nd}) не дают откатиться к его части.
// Не цена: «1С» и число с единицей расстояния («стоит на воротах, читает до 20 метров»).
const PRICE_NUMBER = String.raw`(?<!\p{Nd})(?!1\s{0,2}[сc](?!\p{L}))\p{Nd}{1,15}(?!\p{Nd})(?![.,]\p{Nd})(?!\s{0,2}(?:м|см|мм|км|метр\p{L}{0,3}|сантиметр\p{L}{0,3}|миллиметр\p{L}{0,3}|километр\p{L}{0,3})(?!\p{L}))`;

// Сумма словом без цифр: «пяти тысяч», «2 млн».
const PRICE_AMOUNT_WORD = String.raw`(?<!\p{L})(?:тысяч|тыс|млн|миллион)\p{L}*`;

const PRICE_WORD = String.raw`(?<!\p{L})(?:цена|цены|цену|стоимость|стоит|стоят|обойд[её]тся|выйдет|бюджет\p{L}*|баға\p{L}*)(?!\p{L})`;

// «Какой процент товара теряется?» спрашивает о задаче клиента, а не называет цену.
const AFTER_QUESTION_WORD = String.raw`(?<!(?:какой|какая|какую|сколько)(?:\s{1,5}\p{L}{1,30}){0,2}\s{1,5})`;

export const PRICE_PATTERNS: readonly RegExp[] = [
  new RegExp(String.raw`\p{Nd}[\p{Nd}\s.,]{0,30}${CURRENCY}`, 'giu'),
  /(?<!\p{L})те[нң]ге(?!\p{L})|₸|\$|€/giu,
  new RegExp(String.raw`сэконом${W}*|экономи[яию]\s{1,5}\p{Nd}`, 'giu'),
  new RegExp(
    String.raw`${PRICE_WORD}[^.!?\n]{0,30}?(?:${PRICE_NUMBER}|${PRICE_AMOUNT_WORD})`,
    'giu',
  ),
  // Сверх образца: валюта и проценты словами и одиночный «%»
  /(?<!\p{L})(?:рубл\p{L}*|доллар\p{L}*|евро)(?!\p{L})/giu,
  new RegExp(
    String.raw`${AFTER_QUESTION_WORD}(?<!\p{L})(?:процент\p{L}*|пайыз\p{L}*)(?!\p{L})`,
    'giu',
  ),
  /%/gu,
];

