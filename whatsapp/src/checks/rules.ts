// Данные проверок кодом: перенос docs/reference/checks.py (B-web-email) на WhatsApp.
// В JS \w, \b и \d знают только ASCII даже с флагом u, а в Python 3 они Unicode,
// поэтому «буква, цифра или _» здесь [\p{L}\p{N}_], а цифра \p{Nd}. Квантификаторы перед другими
// частями шаблона ограничены сверху: ответ модели зависит от текста клиента, долгие регулярки
// недопустимы. Шаблоны с флагом g используются только через matchAll или replace;
// CYRILLIC_LETTER и LATIN_LETTER без g: только для test().

const W = String.raw`[\p{L}\p{N}_]`;

/** Не больше трёх предложений в сообщении: в чате «2–3 коротких предложения» вместо 5–8 в письме. */
export const MAX_SENTENCES = 3;

/** Не больше 300 знаков на всё сообщение: «короткие» предложения. */
export const MAX_CHARS = 300;

/** Сколько знаков контекста показывать вокруг найденного фрагмента. */
export const CONTEXT_CHARS = 25;

/** Длинный найденный фрагмент обрезается в замечании: замечания уходят модели при повторе. */
export const MAX_FRAGMENT_CHARS = 60;

/** Номер сравнивается с нашим по последним цифрам: +7, 8 и номер без кода страны совпадают. */
export const PHONE_COMPARE_DIGITS = 10;

/** Хосты, на которые разрешены ссылки. В чате ссылок нет совсем, поэтому список пуст. */
export const ALLOWED_LINK_HOSTS: ReadonlySet<string> = new Set<string>();

/** Аббревиатуры, которые не считаются капслоком. */
export const ALLOWED_CAPS: ReadonlySet<string> = new Set(['RFID', 'ТОО', 'БИН', 'ИИН']);

/** Невидимые символы (\p{Cf}) и управляющие (\p{Cc}) кроме переноса строки: их убирает normalizeDraft. */
export const INVISIBLE_EXCEPT_NEWLINE = /(?!\n)[\p{Cf}\p{Cc}]/gu;

