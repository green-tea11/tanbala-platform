  /(?<!(?:бин|иин)[\s:№]{0,3})(?<![\p{Nd}+])(?:\+\p{Nd}|[78])(?:[\s().,/‒–‑-]{0,4}\p{Nd}){9,14}(?!\p{Nd})/giu;

