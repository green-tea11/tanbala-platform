/** Невидимые символы форматирования и одиночные половинки суррогатных пар: убираются без пробела, слово не рвётся. */
const INVISIBLE = /[\p{Cf}\p{Cs}]/gu;
/** Пробелы, переносы и управляющие символы: сворачиваются в один пробел. */
const BLANKS = /[\p{Cc}\s]+/gu;

/**
 * Одна короткая строка из текста модели: без переносов, невидимых символов и лишних пробелов, не длиннее
 * maxChars знаков. Режет по знакам, а не по кодовым единицам: суррогатная пара (эмодзи) не рвётся пополам.
 * Нужна для выжимки и замечаний проверки: эти тексты идут в промпты, в уведомление менеджеру и в панель,
 * а модель пишет их по словам клиента. Нечего оставлять => пустая строка.
 */
export function cleanLine(text: string, maxChars: number): string {
  const line = text.replace(INVISIBLE, '').replace(BLANKS, ' ').trim();
  const chars = Array.from(line);
  return chars.length <= maxChars ? line : chars.slice(0, maxChars).join('').trimEnd();
}
